"""Bounded, credential-private HTTP primitives; no retries or ambient proxies."""

import asyncio
import json
import math
import os
from pathlib import Path
from urllib.parse import urlsplit


class NewWorkStopped(ValueError):
    pass


def read_json(path):
    path = Path(path)
    if path.stat().st_size > 8 * 1024**2:
        raise ValueError("Input size bound exceeded")
    return json.loads(path.read_text())


def save_json(path, value):
    content = json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as output:
        output.write(content)
        output.flush()
        os.fsync(output.fileno())


def validate_connection(base_url, actors, *, timeout, max_bytes, max_calls):
    u = urlsplit(base_url)
    if (
        (
            u.scheme != "https"
            and not (
                u.scheme == "http" and u.hostname in {"127.0.0.1", "localhost", "::1"}
            )
        )
        or not u.hostname
        or u.username
        or u.password
        or u.query
        or u.fragment
        or u.path not in {"", "/"}
    ):
        raise ValueError("Explicit HTTPS/loopback service root required")
    if (
        not isinstance(actors, dict)
        or not actors
        or len(actors) > 16
        or any(
            not isinstance(k, str) or not isinstance(v, str) or not v or len(v) > 8192
            for k, v in actors.items()
        )
    ):
        raise ValueError("Dedicated actor credentials required")
    if (
        type(max_calls) is not int
        or not 1 <= max_calls <= 100000
        or type(max_bytes) is not int
        or not 1 <= max_bytes <= 16 * 1024**2
        or isinstance(timeout, bool)
        or not isinstance(timeout, (int, float))
        or not math.isfinite(timeout)
        or not 0 < timeout <= 600
    ):
        raise ValueError("Explicit bounded HTTP budgets required")


class BoundedClient:
    def __init__(
        self,
        base_url,
        actors,
        *,
        timeout,
        max_bytes,
        max_calls,
        transport=None,
        stop_event=None,
    ):
        validate_connection(
            base_url, actors, timeout=timeout, max_bytes=max_bytes, max_calls=max_calls
        )
        import httpx

        self.client = httpx.AsyncClient(
            base_url=base_url,
            follow_redirects=False,
            trust_env=False,
            timeout=timeout,
            transport=transport,
        )
        self.actors, self.timeout, self.max_bytes, self.max_calls = (
            actors,
            timeout,
            max_bytes,
            max_calls,
        )
        self.calls = 0
        self.stop_event = stop_event

    def ensure_running(self):
        if self.stop_event is not None and self.stop_event.is_set():
            raise NewWorkStopped("New rehearsal work stopped")

    async def __aenter__(self):
        await self.client.__aenter__()
        return self

    async def __aexit__(self, *args):
        await self.client.__aexit__(*args)

    async def request(
        self,
        method,
        path,
        *,
        actor,
        payload=None,
        key=None,
        params=None,
        allow_after_stop=False,
    ):
        if allow_after_stop and method != "GET":
            raise NewWorkStopped("Only accepted-work readback can bypass stop")
        if not allow_after_stop:
            self.ensure_running()
        if actor not in self.actors or self.calls >= self.max_calls:
            raise ValueError("Actor or call budget refused")
        # Paths are generated by typed callers, never interpreted as arbitrary URLs.
        if (
            not path.startswith("/")
            or path.startswith("//")
            or "?" in path
            or "#" in path
            or "\\" in path
            or ".." in path.split("/")
        ):
            raise ValueError("Invalid internal path")
        self.calls += 1
        headers = {"X-API-Key": self.actors[actor]}
        if key is not None:
            headers["Idempotency-Key"] = key

        async def exchange():
            async with self.client.stream(
                method, path, headers=headers, json=payload, params=params
            ) as response:
                body = bytearray()
                async for chunk in response.aiter_bytes():
                    if len(body) + len(chunk) > self.max_bytes:
                        raise ValueError("Response size bound exceeded")
                    body.extend(chunk)
                return response.status_code, response.headers, bytes(body)

        return await asyncio.wait_for(exchange(), timeout=self.timeout)

    async def json(self, method, path, **kwargs):
        status, headers, body = await self.request(method, path, **kwargs)
        if (
            headers.get("content-type", "").split(";", 1)[0].strip().lower()
            != "application/json"
        ):
            raise ValueError("JSON response required")
        return status, headers, json.loads(body)
